//! Regenerates `src/generated.rs` from the trajectory log's JSON Schema.
//!
//! The record types are never edited by hand: `cargo run -p xtask` rewrites
//! them, and `xtask/tests/generated.rs` fails while the checked-in file
//! differs from what the schema generates.
//!
//! typify reads draft-07 (through schemars 0.8). The schema may be draft
//! 2020-12, so [`normalize`] first rewrites the 2020-12 spellings typify does
//! not know into their draft-07 equivalents: `$defs` -> `definitions`,
//! `prefixItems` -> `items` (an array), and the `items` that follows a
//! `prefixItems` -> `additionalItems`. A closed tuple (`additionalItems:
//! false`) also gets the `maxItems` it implies, which typify needs to see
//! before it emits a Rust tuple. Nothing else changes.

use std::path::PathBuf;

use serde_json::{Map, Value};

/// The vendored schema.
pub fn schema_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../schema/trajectory.schema.json")
}

/// The generated record types.
pub fn generated_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/generated.rs")
}

/// The banner at the top of the generated file.
pub const HEADER: &str = "\
// @generated by `cargo run -p xtask` from
// schema/trajectory.schema.json. Do not edit: change the schema and regenerate.
#![allow(clippy::all, clippy::pedantic, missing_docs, dead_code, unused_imports)]
";

/// Rewrites draft 2020-12 keywords into the draft-07 ones typify reads.
pub fn normalize(value: Value) -> Value {
    match value {
        Value::Object(map) => Value::Object(normalize_object(map)),
        Value::Array(items) => Value::Array(items.into_iter().map(normalize).collect()),
        other => other,
    }
}

fn normalize_object(map: Map<String, Value>) -> Map<String, Value> {
    let mut out = Map::new();
    let has_prefix = map.contains_key("prefixItems");
    for (key, value) in map {
        match key.as_str() {
            "$schema" => {
                out.insert(
                    key,
                    Value::String("http://json-schema.org/draft-07/schema#".into()),
                );
            }
            "$defs" | "definitions" => {
                let defs = normalize(value);
                if let (Some(Value::Object(existing)), Value::Object(new)) =
                    (out.get_mut("definitions"), &defs)
                {
                    existing.extend(new.clone());
                } else {
                    out.insert("definitions".into(), defs);
                }
            }
            "$ref" => {
                let reference = value
                    .as_str()
                    .map(|s| s.replacen("#/$defs/", "#/definitions/", 1))
                    .map(Value::String)
                    .unwrap_or(value);
                out.insert(key, reference);
            }
            "prefixItems" => {
                out.insert("items".into(), normalize(value));
            }
            "items" if has_prefix => {
                out.insert("additionalItems".into(), normalize(value));
            }
            _ => {
                out.insert(key, normalize(value));
            }
        }
    }
    if let (Some(Value::Array(items)), Some(Value::Bool(false))) =
        (out.get("items"), out.get("additionalItems"))
    {
        let len = items.len();
        out.entry("maxItems").or_insert_with(|| Value::from(len));
    }
    out
}

/// Generates the Rust source of the record types from the schema's text.
pub fn generate(schema_text: &str) -> Result<String, Box<dyn std::error::Error>> {
    let value: Value = serde_json::from_str(schema_text)?;
    let normalized = normalize(value);
    let tables = tables(&normalized)?;
    let root: schemars::schema::RootSchema = serde_json::from_value(normalized)?;
    let mut settings = typify::TypeSpaceSettings::default();
    settings.with_struct_builder(false);
    settings.with_derive("PartialEq".to_string());
    let mut space = typify::TypeSpace::new(&settings);
    space.add_root_schema(root)?;
    let file: syn::File = syn::parse2(space.to_stream())?;
    Ok(format!(
        "{HEADER}\n{}\n{tables}",
        prettyplease::unparse(&file)
    ))
}

/// `RECORD_TYPES` and `SCHEMA_VERSION`: what the record types are called on
/// the wire, which typify's untagged enum does not say.
fn tables(schema: &Value) -> Result<String, Box<dyn std::error::Error>> {
    let mut rows = String::new();
    let variants = schema["oneOf"]
        .as_array()
        .ok_or("the schema has no top-level oneOf")?;
    for variant in variants {
        let reference = variant["$ref"]
            .as_str()
            .ok_or("a oneOf entry is not a $ref")?;
        let name = reference.rsplit('/').next().unwrap_or(reference);
        let ty = schema["definitions"][name]["properties"]["type"]["const"]
            .as_str()
            .ok_or_else(|| format!("{name} has no `type` const"))?;
        rows.push_str(&format!("    ({ty:?}, {name:?}),\n"));
    }
    let version = schema["x-schema-version"].as_u64().unwrap_or(1);
    Ok(format!(
        "/// Every record of the schema: its `type` on the wire and its generated type.\n\
         pub const RECORD_TYPES: &[(&str, &str)] = &[\n{rows}];\n\
         /// The format version the schema describes (`x-schema-version`).\n\
         pub const SCHEMA_VERSION: u64 = {version};\n"
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn rewrites_2020_12_tuples_and_defs() {
        let schema = json!({
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "$defs": {"V": {"type": "array", "prefixItems": [{"type": "number"}], "items": false}},
            "oneOf": [{"$ref": "#/$defs/V"}]
        });
        let out = normalize(schema);
        assert_eq!(
            out,
            json!({
                "$schema": "http://json-schema.org/draft-07/schema#",
                "definitions": {"V": {"type": "array", "items": [{"type": "number"}], "additionalItems": false, "maxItems": 1}},
                "oneOf": [{"$ref": "#/definitions/V"}]
            })
        );
    }

    #[test]
    fn draft_07_passes_through() {
        let schema = json!({"definitions": {"A": {"type": "array", "items": [{"type": "string"}], "additionalItems": false, "maxItems": 1}}});
        assert_eq!(normalize(schema.clone()), schema);
    }
}
